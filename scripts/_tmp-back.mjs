import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://localhost:5173/?p=prequal-dashboard&chrome=0&latency=medium', { waitUntil: 'networkidle0' });
await page.evaluate(() => { window.__same = 1; });
const title = () => page.evaluate(() => [new URLSearchParams(location.search).get('p'), location.hash, document.querySelector('.lnrc-app-layout span').textContent.trim(), window.__same === 1]);
const click = (l) => page.evaluate((l) => [...document.querySelectorAll('[role=navigation] *')].filter((e) => e.textContent.trim() === l).pop().click(), l);
await click('Review Queue'); await new Promise((r) => setTimeout(r, 100));
console.log('queue+100ms', await title(), await page.evaluate(() => document.querySelectorAll('.dg-list-header-grid').length));
await new Promise((r) => setTimeout(r, 1200));
// open a row → review with id
await page.evaluate(() => document.querySelector('.dg-list-row').click()); await new Promise((r) => setTimeout(r, 400));
console.log('row click', await title());
await page.goBack(); await new Promise((r) => setTimeout(r, 400)); console.log('back', await title());
await page.goBack(); await new Promise((r) => setTimeout(r, 400)); console.log('back', await title());
await page.goForward(); await new Promise((r) => setTimeout(r, 400)); console.log('forward', await title());
console.log('errors', errors);
await browser.close();
